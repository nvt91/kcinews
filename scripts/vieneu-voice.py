"""KCI offline voice batch. Upstream: pnnbao97/VieNeu-TTS (Apache-2.0).
Model: pnnbao-ump/VieNeu-TTS-v3-Turbo (Apache-2.0).
Native tempo 1x; no atempo, respeed, pitch conversion, or substitute voice.
Only load one model per job; manifest is generated by the validated Node runner.
"""
import argparse
import json
import math
import pathlib
import subprocess
import tempfile
import numpy as np
import soundfile as sf
from vieneu import Vieneu

VOICE = "Thùy Dung"
def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest", required=True, type=pathlib.Path)
    parser.add_argument("--out-dir", required=True, type=pathlib.Path)
    args = parser.parse_args()
    items = json.loads(args.manifest.read_text(encoding="utf-8"))
    if not isinstance(items, list) or not 1 <= len(items) <= 12:
        raise ValueError("Expected 1–12 narration segments")
    args.out_dir.mkdir(parents=True, exist_ok=True)
    model = Vieneu(mode="v3turbo", backend="onnx", device="cpu", precision="fp32", threads=2)
    if VOICE not in [voice_id for _, voice_id in model.list_preset_voices()]:
        raise RuntimeError("Required Thùy Dung preset unavailable; refusing fallback")
    voice = model.get_preset_voice(VOICE)
    sr = int(model.sample_rate)
    if sr != 48000:
        raise RuntimeError(f"Unexpected v3 Turbo source sample rate: {sr}")
    with tempfile.TemporaryDirectory(prefix="kci-vieneu-") as tmp:
        for idx, item in enumerate(items, 1):
            text = item["text"].strip()
            if not 3 <= len(text) <= 2000:
                raise ValueError(f"Invalid text length for segment {idx}")
            # Native 1x: the v3 Turbo infer() implementation has no speed parameter.
            samples = np.asarray(model.infer(text=text, voice=voice), dtype=np.float32).reshape(-1)
            seconds = len(samples) / sr
            if not 2 <= seconds <= 95 or not np.all(np.isfinite(samples)):
                raise RuntimeError(f"Invalid synthesized signal for segment {idx}")
            rms = float(np.sqrt(np.mean(samples**2)))
            if not math.isfinite(rms) or rms < 0.001:
                raise RuntimeError(f"Silent audio for segment {idx}")
            wav = pathlib.Path(tmp) / f"scene-{idx:02}.wav"
            sf.write(str(wav), samples, sr, subtype="PCM_16")
            mp3 = args.out_dir / f"scene-{idx:02}.mp3"
            # Loudness target only; no time-stretch. Final MP4 QC must measure achieved LUFS.
            subprocess.run(["ffmpeg", "-nostdin", "-y", "-v", "error", "-i", str(wav),
                            "-af", "loudnorm=I=-14:TP=-1.5:LRA=11",
                            "-ar", "48000", "-c:a", "libmp3lame", "-b:a", "320k", str(mp3)],
                           check=True, timeout=180)
            subprocess.run(["ffmpeg", "-nostdin", "-v", "error", "-i", str(mp3), "-f", "null", "-"],
                           check=True, timeout=120)
            print(f"VieNeu {VOICE} native 1x | scene {idx} | source {seconds:.2f}s | 48000 Hz", flush=True)
    print("VieNeu batch generated; pronunciation/listening QA still required.", flush=True)

if __name__ == "__main__":
    main()
